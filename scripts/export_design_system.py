#!/usr/bin/env python3
"""Generate design-only assets from canonical tokens and vector paths. No device IO."""
from pathlib import Path
import json,html,argparse
R=Path(__file__).resolve().parents[1];D=R/'design/system'
t=json.loads((D/'tokens.json').read_text());icons=json.loads((D/'icons.json').read_text())
css='/* Generated by scripts/export_design_system.py. */\n:root{\n'
for k,v in t['colors'].items():css+='  --tv-'+k+':'+v+';\n'
for group in ['layout','type']:
 for k,v in t[group].items():css+='  --tv-'+group+'-'+k+':'+str(v)+'px;\n'
css+='}\n'
js='/* Generated design assets, not an Android runtime. */\nwindow.TVSystem='+json.dumps({'tokens':t,'icons':icons},ensure_ascii=False,separators=(',',':'))+';\n'
outputs={D/'tokens.css':css,D/'tv-system.js':js}
for name,paths in icons.items():
 body=''.join('<path d="'+html.escape(p,quote=True)+'"/>' for p in paths)
 outputs[D/'svg'/f'{name}.svg']='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">'+body+'</svg>\n'
symbols=''.join('<symbol id="'+n+'" viewBox="0 0 24 24">'+''.join('<path d="'+html.escape(p,quote=True)+'"/>' for p in pp)+'</symbol>' for n,pp in icons.items())
for name,paths in icons.items():
 body=''.join('<path android:pathData="'+html.escape(v,quote=True)+'" android:fillColor="@android:color/transparent" android:strokeColor="#FFF4F0E8" android:strokeWidth="1.5" android:strokeLineCap="round" android:strokeLineJoin="round"/>' for v in paths)
 outputs[D/'android/drawable'/('ic_tv_'+name+'.xml')]='<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">'+body+'</vector>\n'
colors=''.join('<color name="tv_'+k+'">'+v+'</color>' for k,v in t['colors'].items())
outputs[D/'android/values/colors.xml']='<resources>'+colors+'</resources>\n'
outputs[D/'icons.svg']='<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><defs>'+symbols+'</defs></svg>\n'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
for path,text in outputs.items():
 if args.check:
  if not path.exists() or path.read_text()!=text:raise SystemExit('Generated design asset drift: '+str(path.relative_to(R)))
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
print(('Verified' if args.check else 'Generated')+' design tokens and '+str(len(icons))+' vector icons; no device operation')
